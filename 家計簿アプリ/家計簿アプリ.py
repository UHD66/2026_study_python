import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import japanize_matplotlib

dates = pd.date_range(start="2026-10-01", end="2026-10-20")
categories = ["食費", "交通費", "エンタメ", "光熱費", "日用品"]

data = {
    "日付": np.random.choice(dates, 10),
    "カテゴリ": np.random.choice(categories, 10),
    "金額": np.random.randint(500, 5000, 10)
}

df=pd.DataFrame(data)

df=df.sort_values("日付").reset_index(drop=True)

print(df)
print("="*40)

total1=df.groupby("カテゴリ")["金額"].sum().reset_index()
print(f"{total1}")

total=data["金額"].sum()
print(f"{total}円つかった")

plt.figure(figsize=(8, 5))
plt.bar(categories,total1['金額'],color="red")
plt.grid(axis="y", linestyle="--", alpha=0.7)

plt.title("カテゴリ別支出グラフ")
plt.xlabel("カテゴリ")
plt.ylabel("金額 (円)")

plt.show()